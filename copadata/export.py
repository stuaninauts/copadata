"""export.py: processed tables -> the public data the web site reads (ADR 0006).

Writes into web/public/data/ (licensed CC-BY-SA 4.0, like everything derived from Fjelstul):
- one JSON (for the site) and one CSV (for download) per aggregate table, all built by aggregate.py;
- the full processed tables (matches, goals, team_matches) as CSV and Parquet;
- manifest.json (schema, sources and their pinned commits, tables) and README.md (license, attribution).

The browser only selects and draws these rows; nothing is recomputed in JavaScript.

    python -m copadata.export           # (re)write the export
    python -m copadata.export --check   # exit 1 if the committed export differs from a fresh one
"""
from __future__ import annotations

import json
import math
import sys
import tempfile
from pathlib import Path

import pandas as pd

from copadata import aggregate, config

SCHEMA_VERSION = 1
HISTORY = f"{config.FIRST_HISTORICAL_YEAR}-{config.SEASON - 4}"
CORE_STAGES = ("groups", "knockout")

ATTRIBUTION = (
    "Data for 1986-2022 derived from The Fjelstul World Cup Database © 2023 Joshua C. Fjelstul, Ph.D., "
    "licensed under CC-BY-SA 4.0 (https://creativecommons.org/licenses/by-sa/4.0/), available at "
    "https://www.github.com/jfjelstul/worldcup. Modifications: only men's World Cups from 1986, reshaped and "
    "aggregated by CopaData (https://github.com/stuaninauts/copadata). Data for 2026 from OpenFootball "
    "(https://github.com/openfootball/worldcup.json), public domain (CC0)."
)

README = f"""# CopaData: public data

Aggregates and match-level tables of the FIFA Men's World Cup, {config.FIRST_HISTORICAL_YEAR}-{config.SEASON},
generated by `python -m copadata.export`. Do not edit by hand. Tables, columns and source commits are listed
in `manifest.json`; every rate carries its base: `k` hits out of `n`.

## License

[CC-BY-SA 4.0](https://creativecommons.org/licenses/by-sa/4.0/). Reuse must give the attribution below and share
derived data under the same license.

## Attribution

{ATTRIBUTION}
"""


# --- data ---------------------------------------------------------------------------

def load() -> dict[str, pd.DataFrame]:
    return {
        "matches": pd.read_parquet(config.MATCHES_PARQUET),
        "goals": pd.read_parquet(config.GOALS_PARQUET),
        "team_matches": pd.read_parquet(config.TEAM_MATCHES_PARQUET),
    }


def _with_scopes(df: pd.DataFrame) -> pd.DataFrame:
    """Scope columns: the edition, its format era, and the pooled history (editions before SEASON)."""
    return aggregate.add_era(df).assign(
        edition=df["year"].astype(str),
        history=df["year"].map(lambda y: HISTORY if y < config.SEASON else None),
    )


def _by_scope(fn, frames: list[pd.DataFrame], by: list[str]) -> pd.DataFrame:
    """Run an aggregate over every scope type; `fn(*frames, by=[scope, *by])`."""
    parts = []
    for scope_type, col in (("edition", "edition"), ("era", "era"), ("history", "history")):
        sliced = [f[f[col].notna()] for f in frames]
        out = fn(*sliced, by=[col, *by]).rename(columns={col: "scope"})
        parts.append(out.assign(scope_type=scope_type))
    out = pd.concat(parts, ignore_index=True)
    return out[["scope_type", "scope", *[c for c in out.columns if c not in ("scope_type", "scope")]]]


def tables(data: dict[str, pd.DataFrame]) -> dict[str, tuple[str, pd.DataFrame]]:
    """name -> (description, table). Every table comes from aggregate.py."""
    m, g, tm = (_with_scopes(data[k]) for k in ("matches", "goals", "team_matches"))
    core = m[m["stage"].isin(CORE_STAGES)]
    goals = g[g["stage"].isin(CORE_STAGES)]
    knockout = core[core["stage"] == "knockout"].rename(columns={"round_raw": "round"})
    groups = aggregate.add_matchday(core[core["stage"] == "groups"], tm)
    zones = tm[(tm["stage"] == "groups") & (tm["matchday"] > 1).fillna(False)]
    return {
        "summary": ("Match metrics by scope and stage (groups, knockout).",
                    _by_scope(aggregate.summarize, [core], ["stage"])),
        "knockout_rounds": ("Match metrics of the knockout by scope and round.",
                            _by_scope(aggregate.summarize, [knockout], ["round"])),
        "group_matchdays": ("Group-stage draws and goals by scope and matchday (1-3).",
                            _by_scope(lambda d, by: aggregate.summarize(d, by, ["draw_90", "goals_per_match_90"]),
                                      [groups], ["matchday"])),
        "group_zones": ("Team results on group matchdays 2-3 by zone before the match.",
                        _by_scope(aggregate.summarize_teams, [zones], ["zone_before"])),
        "margins": ("Share of matches by final margin (0, 1, 2, 3+) by scope and stage.",
                    _by_scope(aggregate.margin_distribution, [core], ["stage"])),
        "goal_bands": ("Share of regulation goals by minute band, by scope and stage.",
                       _by_scope(aggregate.goal_bands, [goals], ["stage"])),
        "stoppage_goals": ("Second-half stoppage-time goals (k) per match (n), by scope.",
                           _by_scope(lambda gl, mt, by: aggregate.stoppage_goals_per_match(gl, mt, by),
                                     [g, m], [])),
        "single_tests": ("The single externally defined tests (ADR 0002).", single_tests(core)),
    }


def single_tests(core: pd.DataFrame) -> pd.DataFrame:
    """H1: was the SEASON knockout decided in the final quarter more often than the history?"""
    ko = core[core["stage"] == "knockout"]
    season = ko[ko["year"] == config.SEASON]["decided_final_quarter"]
    past = ko[ko["year"] < config.SEASON]["decided_final_quarter"]
    k, n, rate = int(season.sum()), len(season), float(past.mean())
    return pd.DataFrame([{
        "id": "knockout_final_quarter_vs_history", "metric": "decided_final_quarter", "scope": str(config.SEASON),
        "k": k, "n": n, "null_rate": rate, "null_scope": HISTORY, "alternative": "greater",
        "p_value": aggregate.binomial_upper_tail(k, n, rate),
    }])


# --- serialization ------------------------------------------------------------------

def _clean(v):
    if v is None or v is pd.NA or (isinstance(v, float) and math.isnan(v)):
        return None
    if isinstance(v, float):
        return round(v, 6)
    if hasattr(v, "item"):  # numpy scalars
        return _clean(v.item())
    return v


def _json(df: pd.DataFrame) -> str:
    """A JSON array with one record per line: valid JSON that diffs line by line in a PR."""
    rows = [json.dumps({k: _clean(v) for k, v in r.items()}, ensure_ascii=False)
            for r in df.astype(object).to_dict("records")]
    return "[\n" + ",\n".join(rows) + "\n]\n"


def _csv(df: pd.DataFrame) -> str:
    out = df.copy()
    floats = out.select_dtypes("float").columns
    out[floats] = out[floats].round(6)
    return out.to_csv(index=False, lineterminator="\n")


def write(data: dict[str, pd.DataFrame], out: Path) -> list[Path]:
    """Write the full export into `out`; returns the files written."""
    out.mkdir(parents=True, exist_ok=True)
    written, manifest_tables = [], {}
    for name, (description, df) in tables(data).items():
        for ext, text in (("json", _json(df)), ("csv", _csv(df))):
            path = out / f"{name}.{ext}"
            path.write_text(text, encoding="utf-8")
            written.append(path)
        manifest_tables[name] = {"description": description, "files": [f"{name}.json", f"{name}.csv"],
                                 "rows": len(df), "columns": list(df.columns)}
    for name in ("matches", "goals", "team_matches"):
        df = data[name]
        (out / f"{name}.csv").write_text(_csv(df), encoding="utf-8")
        df.to_parquet(out / f"{name}.parquet", index=False)
        written += [out / f"{name}.csv", out / f"{name}.parquet"]
        manifest_tables[name] = {"description": f"Full processed table ({name}).",
                                 "files": [f"{name}.csv", f"{name}.parquet"],
                                 "rows": len(df), "columns": list(df.columns)}
    years = sorted(int(y) for y in data["matches"]["year"].unique())
    manifest = {
        "schema_version": SCHEMA_VERSION,
        "license": "CC-BY-SA-4.0",
        "attribution": ATTRIBUTION,
        "editions": years,
        "sources": {
            "openfootball": {"repository": "https://github.com/openfootball/worldcup.json",
                             "commit": config.OPENFOOTBALL_COMMIT, "license": "CC0-1.0",
                             "editions": [y for y in years if y == config.SEASON]},
            "fjelstul": {"repository": "https://github.com/jfjelstul/worldcup",
                         "commit": config.FJELSTUL_COMMIT, "license": "CC-BY-SA-4.0",
                         "editions": [y for y in years if y < config.SEASON]},
        },
        "tables": manifest_tables,
    }
    (out / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (out / "README.md").write_text(README, encoding="utf-8")
    return [*written, out / "manifest.json", out / "README.md"]


def check(data: dict[str, pd.DataFrame], out: Path) -> list[str]:
    """Differences between the export in `out` and a fresh one (empty list = up to date)."""
    with tempfile.TemporaryDirectory() as tmp:
        fresh = Path(tmp)
        write(data, fresh)
        names = {p.name for p in fresh.iterdir()}
        current = {p.name for p in out.iterdir()} if out.exists() else set()
        problems = [f"missing: {n}" for n in sorted(names - current)]
        problems += [f"unexpected: {n}" for n in sorted(current - names)]
        for n in sorted(names & current):
            a, b = fresh / n, out / n
            same = (pd.read_parquet(a).equals(pd.read_parquet(b)) if n.endswith(".parquet")
                    else a.read_bytes() == b.read_bytes())
            if not same:
                problems.append(f"outdated: {n}")
    return problems


def main(argv: list[str]) -> int:
    data = load()
    if "--check" in argv:
        problems = check(data, config.EXPORT)
        for p in problems:
            print(f"[export] {p}")
        print("[export] up to date" if not problems else
              f"[export] {len(problems)} difference(s): run `python -m copadata.export`")
        return 1 if problems else 0
    files = write(data, config.EXPORT)
    print(f"[export] {len(files)} files -> {config.EXPORT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
